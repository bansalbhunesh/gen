/**
 * StadiumIQ 2026 — accessible front-end controller.
 *
 * Vanilla ES modules, no framework, no external dependencies — keeps the
 * client tiny and CSP-friendly. Handles accessible tab navigation, populates
 * data-driven controls, and calls the JSON API for each GenAI feature.
 */

const RTL = new Set(['ar']);
const $ = (sel, root = document) => root.querySelector(sel);
const $$ = (sel, root = document) => [...root.querySelectorAll(sel)];

/** Small fetch helper that surfaces API error messages. */
async function api(path, options = {}) {
  const res = await fetch(`/api${path}`, {
    headers: { 'content-type': 'application/json' },
    ...options,
  });
  const data = await res.json().catch(() => ({}));
  if (!res.ok) throw new Error(data.error || `Request failed (${res.status})`);
  return data;
}

/** Render text into an <output>, applying direction for RTL languages. */
function showResult(el, html, { lang } = {}) {
  el.innerHTML = html;
  el.dir = lang && RTL.has(lang) ? 'rtl' : 'ltr';
}

function showError(el, message) {
  showResult(el, `<p class="error" role="alert">⚠️ ${escape(message)}</p>`);
}

function escape(str) {
  return String(str).replace(/[&<>"']/g, (c) =>
    ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c],
  );
}

function sourceBadge(source) {
  return source === 'model'
    ? '<span class="meta">✨ Generated by live AI model</span>'
    : '<span class="meta">Offline engine (no AI key configured)</span>';
}

async function withPending(button, fn) {
  const label = button.textContent;
  button.disabled = true;
  button.textContent = 'Working…';
  try {
    await fn();
  } finally {
    button.disabled = false;
    button.textContent = label;
  }
}

// --- Accessible tabs -------------------------------------------------------
function initTabs() {
  const tabs = $$('.tab');
  const selectTab = (tab) => {
    tabs.forEach((t) => {
      const selected = t === tab;
      t.setAttribute('aria-selected', String(selected));
      t.tabIndex = selected ? 0 : -1;
      $(`#${t.getAttribute('aria-controls')}`).hidden = !selected;
    });
    tab.focus();
  };

  tabs.forEach((tab, i) => {
    tab.addEventListener('click', () => selectTab(tab));
    tab.addEventListener('keydown', (e) => {
      if (e.key === 'ArrowRight' || e.key === 'ArrowLeft') {
        e.preventDefault();
        const dir = e.key === 'ArrowRight' ? 1 : -1;
        selectTab(tabs[(i + dir + tabs.length) % tabs.length]);
      }
    });
  });
}

// --- Data-driven controls --------------------------------------------------
async function initData() {
  // AI mode badge
  try {
    const health = await api('/health');
    const badge = $('#ai-mode');
    badge.textContent = health.aiMode === 'model' ? 'AI: live model' : 'AI: offline';
    badge.classList.add(health.aiMode === 'model' ? 'model' : 'offline');
  } catch {
    $('#ai-mode').textContent = 'AI: unknown';
  }

  // Venue selects
  const { venues } = await api('/venues');
  const venueOptions = venues
    .map((v) => `<option value="${v.id}">${escape(v.name)} — ${escape(v.city)}</option>`)
    .join('');
  $('#concierge-venue').innerHTML =
    '<option value="">Any / not sure</option>' + venueOptions;
  $('#navigate-venue').innerHTML = venueOptions;
  $('#crowd-venue').innerHTML = venueOptions;

  // Translation target languages (reuse header <select> options)
  $('#translate-target').innerHTML = $('#language').innerHTML;
  $('#translate-target').value = 'es';

  await loadWayfindingNodes($('#navigate-venue').value);
}

async function loadWayfindingNodes(venueId) {
  const fromSel = $('#navigate-from');
  const toSel = $('#navigate-to');
  try {
    const { wayfindingNodes, hasWayfinding } = await api(`/venues/${venueId}`);
    if (!hasWayfinding || wayfindingNodes.length === 0) {
      const msg = '<option value="">No interactive map for this venue yet</option>';
      fromSel.innerHTML = msg;
      toSel.innerHTML = msg;
      return;
    }
    const opts = wayfindingNodes
      .map((n) => `<option value="${n.id}">${escape(n.label)}</option>`)
      .join('');
    fromSel.innerHTML = opts;
    toSel.innerHTML = opts;
    toSel.selectedIndex = Math.min(wayfindingNodes.length - 1, 4);
  } catch (err) {
    fromSel.innerHTML = `<option value="">${escape(err.message)}</option>`;
    toSel.innerHTML = fromSel.innerHTML;
  }
}

// --- Feature handlers ------------------------------------------------------
function initConcierge() {
  const form = $('#concierge-form');
  const out = $('#concierge-output');
  form.addEventListener('submit', (e) => {
    e.preventDefault();
    const button = $('button', form);
    withPending(button, async () => {
      try {
        const result = await api('/concierge', {
          method: 'POST',
          body: JSON.stringify({
            question: $('#concierge-question').value,
            language: $('#language').value,
            venueId: $('#concierge-venue').value || undefined,
          }),
        });
        showResult(
          out,
          `<h3>Answer</h3><p>${escape(result.answer)}</p>${sourceBadge(result.source)}`,
          { lang: result.language },
        );
      } catch (err) {
        showError(out, err.message);
      }
    });
  });
}

function initNavigate() {
  const form = $('#navigate-form');
  const out = $('#navigate-output');
  $('#navigate-venue').addEventListener('change', (e) => loadWayfindingNodes(e.target.value));
  form.addEventListener('submit', (e) => {
    e.preventDefault();
    const button = $('button', form);
    withPending(button, async () => {
      try {
        const result = await api('/navigate', {
          method: 'POST',
          body: JSON.stringify({
            venueId: $('#navigate-venue').value,
            from: $('#navigate-from').value,
            to: $('#navigate-to').value,
            accessibleOnly: $('#navigate-accessible').checked,
          }),
        });
        showResult(
          out,
          `<h3>Directions (${result.estimatedWalkMinutes} min · ${result.totalDistanceMeters} m)</h3>` +
            `<p>${escape(result.directions)}</p>${sourceBadge(result.source)}`,
        );
      } catch (err) {
        showError(out, err.message);
      }
    });
  });
}

function initCrowd() {
  const form = $('#crowd-form');
  const out = $('#crowd-output');
  form.addEventListener('submit', (e) => {
    e.preventDefault();
    const button = $('button', form);
    withPending(button, async () => {
      try {
        const result = await api(`/crowd/${$('#crowd-venue').value}`);
        const zones = result.zones
          .map(
            (z) =>
              `<li class="zone-card status-${z.status}"><div class="name">${escape(z.zone)}</div>` +
              `<div class="bar"><span style="width:${Math.round(z.occupancy * 100)}%"></span></div>` +
              `<div class="val"><span class="dot"></span>${Math.round(z.occupancy * 100)}% · ${z.status}</div></li>`,
          )
          .join('');
        showResult(
          out,
          `<h3>${escape(result.venue.name)} — overall: ${escape(result.overallStatus)}</h3>` +
            `<ul class="zones">${zones}</ul>` +
            `<h3>Recommended actions</h3><p>${escape(result.recommendations)}</p>` +
            sourceBadge(result.source),
        );
      } catch (err) {
        showError(out, err.message);
      }
    });
  });
}

function initTranslate() {
  const form = $('#translate-form');
  const out = $('#translate-output');
  form.addEventListener('submit', (e) => {
    e.preventDefault();
    const button = $('button', form);
    withPending(button, async () => {
      try {
        const target = $('#translate-target').value;
        const result = await api('/translate', {
          method: 'POST',
          body: JSON.stringify({ text: $('#translate-text').value, target }),
        });
        showResult(out, `<h3>Translation</h3><p>${escape(result.text)}</p>${sourceBadge(result.source)}`, {
          lang: result.target,
        });
      } catch (err) {
        showError(out, err.message);
      }
    });
  });
}

// --- Bootstrap -------------------------------------------------------------
initTabs();
initConcierge();
initNavigate();
initCrowd();
initTranslate();
initData().catch((err) => showError($('#concierge-output'), `Failed to load: ${err.message}`));
